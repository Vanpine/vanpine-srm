def build_system_prompt(question: str, route: str = "agent") -> str:
    """构建 system prompt（2026-10 拆分：knowledge / agent 两套，降低注意力污染）。

    route:
      knowledge → 文档问答/引用/拒答 规则，不含业务工具、标识展示等业务规则
      agent     → 业务工具选择/状态展示/写操作确认 规则，不含知识检索规则
    检索资料不再进 system prompt（由 build_messages 放到 user 消息），避免
    知识规则与业务规则互相干扰。

    Args:
        question: 当前提问（用于注入天气/业务领域锚点）
        route: knowledge | agent

    Returns:
        system prompt 文本
    """
    weather_question = is_weather_question(question)

    # 拼接顺序 = 缓存友好顺序：静态前缀（每轮完全一致）→ 路由规则 → 动态规则。
    # 动态部分只允许加在末尾，否则上游前缀缓存整段失效。
    # 锚点（DOMAIN_HINTS 命中项）按关键词出现位置取第一条，对同一问题顺序稳定。
    anchor = _domain_anchor(question)
    if route == "knowledge":
        # 知识问答：静态前缀 + 知识引用/拒答规则
        parts = [KNOWLEDGE_STATIC_PROMPT]
        if weather_question:
            parts.append(LIVE_WEATHER_RULE)
    else:
        # agent（业务工具）路径：静态前缀 + 标识展示 + 手动执行
        parts = [AGENT_STATIC_PROMPT]
        if weather_question:
            parts.append(LIVE_WEATHER_RULE)
    # 业务锚点放最后：它是唯一随本轮问题变化的规则块，放末尾保证前面全是稳定前缀
    if anchor:
        parts.append(anchor)
    return "\n".join(parts)


def _domain_anchor(question: str) -> str | None:
    """按问题选一条业务领域锚点（只取第一个命中，避免多领域混淆）。"""
    question_lower = (question or "").lower()
    for keyword, hint in DOMAIN_HINTS.items():
        if keyword in question_lower:
            return hint
    return None

